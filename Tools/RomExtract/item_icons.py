"""The icons the game's menus draw for its objects, and which object draws which.

The menus draw an object with frame ITEM_TYPE_CATEGORIES[ItemInfo.type] of the menu sheet (ITEM_FUNCS.getCategory), so
there is one icon per type of object, not per object. The sheet is the file FILE_MENU_SPRITES and its texture, with the
CLUTs in it, the archive FILE_FONT, which loadFont sends to VRAM (0x140, 0). File numbers of the European disc.

Writes, from a copy of the game and the matching decompilations (ReGame-Labs/dw3_decomp, MIT; the item names of
markisha64/ddw3):
  - one transparent PNG per frame in use, native size (12 px).
  - a generated TypeScript file with the icon of each equipment and object of the database. An equipment's id is the game's
    item id; the objects of the database have ids of their own, so they go by their name.

Usage (needs Pillow and numpy; paths as in the README):
  DW3_ISO=game.iso DW3_DECOMP=dw3_decomp DW3_DDW3=ddw3 python3 Tools/RomExtract/item_icons.py [--png DIR] [--ts FILE]
"""
import argparse
import json
import os
import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent / "render"))
os.environ.setdefault("DW3_OUT", "")  # render/ asks for it; nothing here is written there
from dwr import Sheet, Vram, file_by_index, pack_entries_game  # noqa: E402

FILE_MENU_SPRITES = 0x286
FILE_FONT = 0x287
TEXTURE = (0x140, 0)
BOOSTER_TYPE = 0x62  # CARD_PACK_CATEGORY


def item_frames(decomp):
    """Game item id -> frame of the menu sheet."""
    source = (Path(decomp) / "src/engine/game/items.c").read_text()
    table = re.search(r"ITEM_TYPE_CATEGORIES\[32\] = \{(.*?)\}", source, re.S).group(1)
    categories = [int(value, 16) for value in re.findall(r"0x[0-9A-F]+", table)]
    rows = re.findall(r"/\* 0x([0-9A-F]{3}) \*/ \{\{[^}]*\}, [^,]+, [^,]+, ITEM_KIND_\w+, (0x[0-9A-F]+|\d+)\}", source)
    return {int(item, 16): categories[int(kind, 0)] for item, kind in rows}


def icon(vram, sheet, frame):
    """A frame of one 4-bit part as RGBA; colour 0 is the only transparent one, as the GPU has it."""
    _, _, parts = sheet.frame(frame)
    u, v, w, h, clut_x, clut_y, _ = sheet.parts[parts[0][0]]
    x, y = TEXTURE
    nibbles = x * 4 + u + np.arange(w)
    rows = vram.m[(y + v + np.arange(h)) & 511].view(np.uint8).reshape(h, 2048)
    texels = rows[:, nibbles // 2]
    indexes = np.where(nibbles % 2 == 0, texels & 15, texels >> 4)
    left = (x + clut_x) & ~15
    colors = vram.m[y + clut_y, left:left + 16][indexes].astype(np.int32)
    red, green, blue = colors & 31, (colors >> 5) & 31, (colors >> 10) & 31
    channels = [(red << 3) | (red >> 2), (green << 3) | (green >> 2), (blue << 3) | (blue >> 2), (colors != 0) * 255]
    return Image.fromarray(np.stack(channels, -1).astype(np.uint8), "RGBA")


def database_icons(frames, names):
    """Id of the database -> frame, for its equipment and its objects."""
    database = ROOT / "Frontend/src/database"
    locale = ROOT / "Frontend/src/i18n/locales/en-US/consumable-item/consumable-item.json"
    out = {}
    for item in json.loads((database / "equipment.json").read_text()):
        out[item] = frames[int(item)]
    by_name = {name: item for item, name in enumerate(names) if item in frames}
    for item, entry in json.loads(locale.read_text())["consumableItems"].items():
        out[item] = frames[by_name[entry["name"]]]
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--png", default=ROOT / "Frontend/src/handheld/assets/items", type=Path)
    parser.add_argument("--ts", default=ROOT / "Frontend/src/handheld/item-icons.ts", type=Path)
    args = parser.parse_args()

    names_file = Path(os.environ["DW3_DDW3"]) / "lang_file/dw2003/eng/esitmnam.toml"
    names = re.findall(r'^\s*"(.*)",\s*$', names_file.read_text(encoding="utf8"), re.M)
    icons = database_icons(item_frames(os.environ["DW3_DECOMP"]), names)

    sheet = Sheet(pack_entries_game(file_by_index(FILE_MENU_SPRITES))[0])
    vram = Vram()
    vram.load_archive(pack_entries_game(file_by_index(FILE_FONT))[0], *TEXTURE, *TEXTURE)
    args.png.mkdir(parents=True, exist_ok=True)
    for frame in {*icons.values(), BOOSTER_TYPE}:
        icon(vram, sheet, frame).save(args.png / f"item-{frame:02x}.png")

    lines = [
        "// Generated by Tools/RomExtract/item_icons.py: do not edit.",
        "// The icon the game's menus draw for each equipment and object of the database, one per type of object. The facts",
        "// are from the matching decompilation of the European version, ReGame-Labs/dw3_decomp (MIT).",
        "",
        f'export const BoosterIcon = "item-{BOOSTER_TYPE:02x}";',
        "",
        "export const ItemIcons: Readonly<Record<string, string>> = {",
        *(f'  "{item}": "item-{frame:02x}",' for item, frame in icons.items()),
        "};",
        "",
    ]
    args.ts.write_text("\n".join(lines))
    print(f"{len(icons)} objects, {len({*icons.values(), BOOSTER_TYPE})} icons")


if __name__ == "__main__":
    main()
