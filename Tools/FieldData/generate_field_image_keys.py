#!/usr/bin/env python3
"""Generate numeric RAM field-mode -> extracted WSTAG image keys for the EU game.

Uses the shared EU table readers and the extractor's generated numeric stage facts.
The live map follows the game's main and extra chapter tables. Callers without
chapter information can only resolve modes with an unambiguous tile map.
No disc or game images needed.

Usage: python3 Tools/FieldData/generate_field_image_keys.py --decomp /path/to/dw3_decomp
"""
import argparse
import gzip
import json
from pathlib import Path
import re

from generate_quest_conditions import extra_chapter_stages
from stage_data import european_stages, preprocess

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "Frontend/src/handheld/field-image-keys.ts"
STAGE_FACTS = ROOT / "Android/extractor/src/main/resources/extractor/stages.json.gz"
# These stage overlays draw maps with sprite sheets instead of a tile-map file.
CUSTOM_MAP_STAGES = {415, 815}


def check_unique_modes(text):
    # The shared readers return dicts; reject duplicate source rows before one
    # could silently overwrite another. Special non-WSTAG handlers stay unmapped.
    for name in ("FIELDSTG_stages", "FIELDSTG_extraStages"):
        start = text.index(f"StageEntry {name}[]")
        block = text[start:text.index("};", start)]
        modes = re.findall(r"\{(\d+), \d+, WSTAG\d+_startStage\}", block)
        if len(modes) != len(set(modes)):
            raise ValueError(f"Duplicate mode in {name}")


def image_stages(table, stages):
    result = {}
    for mode, stage in table.items():
        info = stages.get(str(stage))
        if not isinstance(info, dict) or "mapFile" not in info:
            raise ValueError(f"Stage {stage} is missing from extractor facts")
        map_file = info["mapFile"]
        if map_file is not None and (type(map_file) is not int or not 0 <= map_file < 2382):
            raise ValueError(f"Stage {stage} has an invalid map file")
        if map_file is not None or stage in CUSTOM_MAP_STAGES:
            result[mode] = stage
    return result


def source_for(main, extra, ambiguous):
    def rows(stages):
        return "\n".join(f"  {mode}: {stage}," for mode, stage in sorted(stages.items()))

    return f"""// Generated by Tools/FieldData/generate_field_image_keys.py; numeric EU facts only.
const MAIN_IMAGE_STAGES: Readonly<Partial<Record<number, number>>> = {{
{rows(main)}
}};

const EXTRA_IMAGE_STAGES: Readonly<Partial<Record<number, number>>> = {{
{rows(extra)}
}};

const CHAPTER_DEPENDENT_MAPS = new Set([{", ".join(map(str, sorted(ambiguous)))}]);

/** RAM field mode to an extracted WSTAG key. Only the live game supplies its chapter. */
export function fieldMapImageKey(mode: number, extraChapter?: boolean): string | null {{
  if (!Number.isSafeInteger(mode) || mode < 0) return null;
  if (extraChapter === undefined && CHAPTER_DEPENDENT_MAPS.has(mode)) return null;
  const stage = (extraChapter ? EXTRA_IMAGE_STAGES[mode] : undefined) ?? MAIN_IMAGE_STAGES[mode];
  return stage === undefined ? null : `maps/${{stage}}`;
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--decomp", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    text = preprocess((args.decomp / "src/field/field_mode/data/fieldstg.c").read_text(encoding="utf-8"))
    check_unique_modes(text)
    extra, main_stages, _ = extra_chapter_stages(args.decomp)
    if main_stages != european_stages(args.decomp) or not main_stages:
        raise ValueError("Shared EU stage readers disagree or the table is empty")
    stages = json.loads(gzip.decompress(STAGE_FACTS.read_bytes()))
    main_images = image_stages(main_stages, stages)
    extra_images = image_stages(extra, stages)
    ambiguous = {mode for mode in main_images.keys() & extra_images.keys()
                 if stages[str(main_images[mode])]["mapFile"] != stages[str(extra_images[mode])]["mapFile"]}
    images = main_images.keys() | extra_images.keys()
    without_map = (main_stages.keys() | extra.keys()) - images
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(source_for(main_images, extra_images, ambiguous), encoding="utf-8")
    catalog = json.loads((ROOT / "Frontend/src/database/map.json").read_text(encoding="utf-8"))
    catalog_modes = {int(mode, 16) for mode in catalog}
    print(json.dumps({
        "mainStageModes": len(main_stages), "extraStageModes": len(extra),
        "resolvedModes": len(images), "chapterAmbiguousModes": len(ambiguous),
        "withoutMapFileModes": len(without_map),
        "catalog": {"total": len(catalog_modes), "resolved": len(catalog_modes & images),
                    "chapterAmbiguous": len(catalog_modes & set(ambiguous)),
                    "withoutMapFile": len(catalog_modes & set(without_map)),
                    "outsideWstagTables": len(catalog_modes - main_stages.keys() - extra.keys())},
    }, sort_keys=True))


if __name__ == "__main__":
    main()
