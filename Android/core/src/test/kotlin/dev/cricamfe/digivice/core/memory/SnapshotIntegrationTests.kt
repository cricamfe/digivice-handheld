import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * The readers against the real RAM snapshots and the real definitions. The expected values come from the golden
 * state generated by the original C# backend for the same snapshot.
 */
class SnapshotIntegrationTests {
    private companion object {
        const val SNAPSHOT = "antes-patrulheiro-opcional-1-centro-admin-subsolo-andar-1"
    }

    private val addresses = TestEnvironment.createAddressesRepository()

    private fun snapshot(name: String) = TestEnvironment.snapshot(name)

    private fun digimonReaderFor(memoryReader: MemoryReader) = DigimonReader(
        memoryReader,
        DigievolutionSlotReader(),
        StoredDigievolutionReader(),
        InBattleReader(memoryReader),
    )

    @Test
    fun `player values match the known snapshot`() {
        val player = PlayerReader(MemoryReader(snapshot(SNAPSHOT))).read(addresses.getPlayerAddresses())

        assertEquals(45846, player.bits)
        assertEquals(0x21A, player.mapId.toInt())
    }

    @Test
    fun `player previous map id matches the golden state`() {
        val player = PlayerReader(MemoryReader(snapshot(SNAPSHOT))).read(addresses.getPlayerAddresses())

        assertEquals(0x1000, player.previousMapId.toInt())
    }

    @Test
    fun `important items and auctions match the golden state`() {
        val memoryReader = MemoryReader(snapshot(SNAPSHOT))

        val items = ImportantItemsReader(memoryReader).read(addresses.getImportantItemsAddresses())
        assertNotEquals(0.toUByte(), items.treeBoots)
        assertNotEquals(0.toUByte(), items.fishingPole)
        assertEquals(0.toUByte(), items.asukaTrophy)
        assertEquals(0.toUByte(), items.sunTrophy)

        val auctions = AuctionsReader(memoryReader).read(addresses.getAuctionsAddresses())
        assertNotEquals(0.toUByte(), auctions.divineBarrier)
        assertNotEquals(0.toUByte(), auctions.hazardShield)
        assertEquals(0.toUByte(), auctions.sniperShield)
        assertNotEquals(0.toUByte(), auctions.dramonShield)
        assertEquals(0.toUByte(), auctions.yinYangWand)
        assertEquals(0.toUByte(), auctions.hazardFang)
    }

    @Test
    fun `digimon battle matches the golden state`() {
        val memoryReader = MemoryReader(snapshot(SNAPSHOT))

        val battle = DigimonBattleReader(memoryReader, EnemyReader(memoryReader))
            .read(addresses.getDigimonBattleAddresses(), addresses.getEnemyAddresses())

        assertEquals(0.toUByte(), battle.field)
        assertEquals(134, battle.enemy.id)
        assertEquals(192, battle.enemy.groupId)
        assertEquals(0, battle.enemy.hp.current)
        assertEquals(816, battle.enemy.hp.max)
    }

    @Test
    fun `party digimon values match the golden state`() {
        val memoryReader = MemoryReader(snapshot(SNAPSHOT))
        val party = PartyReader(DigimonSlotReader(memoryReader)).read(addresses.getPartyAddresses())
        val digimonReader = digimonReaderFor(memoryReader)

        fun readSlot(slotNumber: Int) = party.slotsResource.single { it.index == slotNumber }.let { slot ->
            slot to digimonReader.read(
                addresses.getDigimonAddressById(slot.digimonId)!!,
                addresses.getDigimonStatusAddresses(),
                addresses.getInBattleAddresses(),
                slot.index,
            )
        }

        val (slot1, digimon1) = readSlot(1)
        assertEquals(0, slot1.digimonId)
        assertNotNull(digimon1)
        digimon1!!
        assertEquals(25, digimon1.level)
        assertEquals(10, digimon1.tp)
        assertEquals(358, digimon1.blast)
        assertEquals(14035, digimon1.experience)
        assertEquals(1862, digimon1.hp.current)
        assertEquals(2079, digimon1.hp.max)
        assertEquals(1230, digimon1.mp.current)
        assertEquals(1272, digimon1.mp.max)
        assertEquals(1862, digimon1.inBattle.hp.current)
        assertEquals(367, digimon1.attributes.strength)
        assertEquals(172, digimon1.attributes.charisma)
        assertEquals(104, digimon1.elements.fire)
        assertEquals(129, digimon1.elements.dark)
        assertEquals(219, digimon1.equipments.head)
        assertEquals(314, digimon1.equipments.accessory2)
        assertEquals(389, digimon1.activeDigievolutionId)
        assertEquals(listOf(386, 5, 389), digimon1.digievolutions.map { it.digievolutionId })
        assertEquals(listOf(386 to 99, 5 to 1, 389 to 18), digimon1.storedDigievolutions.map { it.digievolutionId to it.level })
        assertEquals(listOf(985, 0, 176), digimon1.storedDigievolutions.map { it.dvexp })

        val (slot2, digimon2) = readSlot(2)
        assertEquals(7, slot2.digimonId)
        digimon2!!
        assertEquals(20, digimon2.level)
        assertEquals(8562, digimon2.experience)
        assertEquals(1206, digimon2.hp.max)
        assertEquals(56, digimon2.activeDigievolutionId)
        assertEquals(listOf(20, 56, 234, 211), digimon2.storedDigievolutions.map { it.digievolutionId })
    }

    @Test
    fun `every snapshot can be read by every reader`() {
        for (name in TestEnvironment.snapshotNames()) {
            val memoryReader = MemoryReader(snapshot(name))
            val requisiteReader = RequisiteReader(memoryReader)
            val questReader = QuestReader(requisiteReader, StepReader(memoryReader, requisiteReader))

            PlayerReader(memoryReader).read(addresses.getPlayerAddresses())
            CardBattleReader(memoryReader).read(addresses.getCardBattleAddresses())
            NpcsReader(memoryReader).read(addresses.getNpcsAddresses())
            val quests = listOf(addresses.getMainQuest()) +
                addresses.getAllSideQuests() +
                addresses.getAllLegendaryWeapons() +
                addresses.getAllDriAgents() +
                addresses.getAllDuelIsland()
            val resources = quests.map { questReader.read(it) }
            assertEquals(quests.map { it.id }, resources.map { it.id }, name)

            val party = PartyReader(DigimonSlotReader(memoryReader)).read(addresses.getPartyAddresses())
            val digimonReader = digimonReaderFor(memoryReader)
            for (slot in party.slotsResource) {
                val digimonAddress = addresses.getDigimonAddressById(slot.digimonId) ?: continue
                val digimon = digimonReader.read(
                    digimonAddress,
                    addresses.getDigimonStatusAddresses(),
                    addresses.getInBattleAddresses(),
                    slot.index,
                )
                assertNotNull(digimon, "$name slot ${slot.index}")
            }
            assertTrue(party.slotsResource.isNotEmpty(), name)
        }
    }
}
