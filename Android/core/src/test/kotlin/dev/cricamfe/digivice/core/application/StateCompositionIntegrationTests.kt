package dev.cricamfe.digivice.core.application

import dev.cricamfe.digivice.core.CoreModule
import dev.cricamfe.digivice.core.domain.models.State
import dev.cricamfe.digivice.core.memory.TestEnvironment
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertNotNull
import org.junit.jupiter.api.Assertions.assertNull
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * The whole core, wired by `CoreModule`, against the real RAM snapshots and the real definitions. The golden state
 * (`src/test/resources/golden/state`) was generated by the original C# backend from the same snapshots; the wire format
 * of all 18 snapshots against it is checked, strictly, by `StateGoldenTest`.
 */
class StateCompositionIntegrationTests {
    private companion object {
        const val SNAPSHOT = "antes-patrulheiro-opcional-1-centro-admin-subsolo-andar-1"
    }

    private fun composeState(snapshotName: String): State {
        val module = CoreModule(
            accessor = TestEnvironment.snapshot(snapshotName),
            readDefinition = TestEnvironment.definitions::readText,
            listDefinitions = TestEnvironment.definitions::listFiles,
        )
        return module.stateComposer.compose()
    }

    @Test
    fun `known snapshot composes kotemon first and the known bits`() {
        val state = composeState(SNAPSHOT)

        assertEquals(45846, state.player.bits)
        assertEquals("021A", state.player.mapId)

        val first = state.party.slots[0]
        assertEquals(1, first.index)
        assertEquals(0, first.digimonId)
        val kotemon = first.digimon
        assertNotNull(kotemon)
        kotemon!!
        assertEquals(25, kotemon.level)
        assertEquals(1862, kotemon.hp.current)
        assertEquals(2079, kotemon.hp.max)
    }

    @Test
    fun `known snapshot composes the second and third members and the rest of the state`() {
        val state = composeState(SNAPSHOT)

        assertEquals(3, state.party.slots.size)
        assertEquals(listOf(0, 7, 6), state.party.slots.map { it.digimonId })
        assertEquals(20, state.party.slots[1].digimon!!.level)
        assertEquals(1206, state.party.slots[1].digimon!!.hp.max)

        assertTrue(state.importantItems.treeBoots)
        assertTrue(state.importantItems.fishingPole)
        assertTrue(state.auctions.divineBarrier)
        assertNull(state.cardBattle.id)
        assertEquals(134, state.digimonBattle.enemy!!.id)
        assertEquals(133, state.journal.mainQuest.steps.size)
    }
}
