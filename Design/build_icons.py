FLAT = {"fire", "thunder", "ice", "card", "signpost"}


def parse(name):
    rows = [row.ljust(SIZE, ".") for row in GLYPHS[name].strip("\n").split("\n")]
    if len(rows) > SIZE or any(len(row) != SIZE for row in rows):
        raise ValueError(f"{name}: {len(rows)} rows, widths {[len(row) for row in rows]}")
    top = (SIZE - len(rows)) // 2
    return ["." * SIZE] * top + rows + ["." * SIZE] * (SIZE - len(rows) - top)


def shade(rows, flat=False):
    def cell(x, y):
        return rows[y][x] if 0 <= x < SIZE and 0 <= y < SIZE else "."

    bounds = {}
    for y in range(SIZE):
        for x in range(SIZE):
            char = cell(x, y)
            if char not in ".x":
                left, top, right, bottom = bounds.get(char, (x, y, x, y))
                bounds[char] = (min(left, x), min(top, y), max(right, x), max(bottom, y))

    pixels = {}
    for y in range(SIZE):
        for x in range(SIZE):
            char = cell(x, y)
            if char == ".":
                continue
            if char == "x":
                pixels[(x, y)] = INK
                continue
            spec, light, mid, dark, _ = RAMPS[char]
            left, top, right, bottom = bounds[char]
            span = max(1, (right - left) + (bottom - top))
            depth = ((x - left) + (y - top)) / span
            open_right = cell(x + 1, y) in ".x"
            open_down = cell(x, y + 1) in ".x"
            open_left = cell(x - 1, y) in ".x"
            open_up = cell(x, y - 1) in ".x"
            if open_right or open_down:
                color = dark
            elif open_up and open_left:
                color = spec
            elif open_up or open_left:
                color = light
            elif flat:
                color = mid
            elif depth < 0.42:
                color = light
            elif depth < 0.72:
                color = mid
            else:
                color = dark
            pixels[(x, y)] = color

    outline = {}
    for y in range(SIZE):
        for x in range(SIZE):
            char = cell(x, y)
            if char in ".x":
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                neighbour = (x + dx, y + dy)
                if neighbour not in pixels and neighbour not in outline:
                    outline[neighbour] = RAMPS[char][4]
    return {**outline, **pixels}


def to_svg(pixels):
    size = SIZE + 2
    rects = []
    placed = {(x + 1, y + 1): color for (x, y), color in pixels.items()}
    for y in range(size):
        x = 0
        while x < size:
            color = placed.get((x, y))
            if color is None:
                x += 1
                continue
            run = 1
            while placed.get((x + run, y)) == color:
                run += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{color}"/>')
            x += run
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}" '
        'shape-rendering="crispEdges">' + "".join(rects) + "</svg>\n"
    )


